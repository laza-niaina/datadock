#!/usr/bin/env node
/**
 * Regenerates the `ENGINE_SVGS` block in `src/ui/icons.ts` from the engine
 * mark files in `resources/icon/`, byte-exact, with XML declarations,
 * DOCTYPEs and comments stripped so the markup is safe to inline in webviews.
 *
 * Run after adding or touching an engine mark:
 *   node scripts/gen-engine-svgs.cjs
 */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const iconDir = path.join(root, 'resources', 'icon');
const target = path.join(root, 'src', 'ui', 'icons.ts');

/** engine key -> mark file (relative to resources/icon/). */
const MARKS = [
  ['mysql', 'mysql.svg'],
  ['mariadb', 'mariadb.svg'],
  ['postgresql', 'pg_server.svg'],
  ['sqlite', 'sqlite-icon.svg'],
  ['mssql', 'mssql.svg'],
  ['fallback', 'database-container.svg'],
];

const out = {};
for (const [key, file] of MARKS) {
  let content = fs.readFileSync(path.join(iconDir, file), 'utf8').trim();
  content = content
    .replace(/^<\?xml[\s\S]*?\?>\s*/, '')
    .replace(/^<!DOCTYPE[\s\S]*?>\s*/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim();
  out[key] = content;
}

const generated = Object.keys(out)
  .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(out[key])},`)
  .join('\n');

let source = fs.readFileSync(target, 'utf8');
const begin = source.indexOf('// __ENGINE_SVGS_BEGIN__');
const end = source.indexOf('// __ENGINE_SVGS_END__');
if (begin < 0 || end < 0 || end <= begin) {
  console.error('gen-engine-svgs: marker comments not found in ' + target);
  process.exit(1);
}
const injected =
  `// __ENGINE_SVGS_BEGIN__\n` +
  `export const ENGINE_SVGS: Record<string, string> = {\n` +
  `  // Generated by scripts/gen-engine-svgs.cjs from resources/icon/*.svg.\n` +
  `${generated}\n` +
  `};\n` +
  `// __ENGINE_SVGS_END__`;
source = source.slice(0, begin) + injected + source.slice(end + '// __ENGINE_SVGS_END__'.length);
fs.writeFileSync(target, source);

const totals = Object.keys(out)
  .map((key) => `${key}:${out[key].length}`)
  .join(' ');
console.log(`gen-engine-svgs: injected engine marks into src/ui/icons.ts (${totals})`);